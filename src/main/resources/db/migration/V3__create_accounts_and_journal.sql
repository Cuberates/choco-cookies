CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(40) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL
);

CREATE TABLE journal_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    bowling_date DATE NOT NULL,
    league_name VARCHAR(160) NOT NULL,
    alley_name VARCHAR(160) NOT NULL,
    location VARCHAR(160) NOT NULL,
    games INTEGER NOT NULL CHECK (games BETWEEN 1 AND 100),
    pins INTEGER NOT NULL CHECK (pins >= 0 AND pins <= games * 300),
    notes VARCHAR(2000) NOT NULL
);
CREATE INDEX journal_entry_user_date_idx ON journal_entry(user_id, bowling_date);

CREATE TABLE journal_entry_ball (
    entry_id BIGINT NOT NULL REFERENCES journal_entry(id) ON DELETE CASCADE,
    ball_id BIGINT NOT NULL REFERENCES bowling_ball(id),
    PRIMARY KEY (entry_id, ball_id)
);

CREATE TABLE SPRING_SESSION (
    PRIMARY_ID CHAR(36) NOT NULL PRIMARY KEY,
    SESSION_ID CHAR(36) NOT NULL,
    CREATION_TIME BIGINT NOT NULL,
    LAST_ACCESS_TIME BIGINT NOT NULL,
    MAX_INACTIVE_INTERVAL INT NOT NULL,
    EXPIRY_TIME BIGINT NOT NULL,
    PRINCIPAL_NAME VARCHAR(100)
);
CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION(SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION(EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION(PRINCIPAL_NAME);
CREATE TABLE SPRING_SESSION_ATTRIBUTES (
    SESSION_PRIMARY_ID CHAR(36) NOT NULL REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE,
    ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
    ATTRIBUTE_BYTES BYTEA NOT NULL,
    PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME)
);
